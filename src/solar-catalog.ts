import type { CatalogEntry } from './library'

type Entry = Omit<CatalogEntry, 'scene'>
type Source = readonly [label: string, url: string]

const dwarfParameters: Source = ['Физические параметры карликовых планет · JPL', 'https://ssd.jpl.nasa.gov/planets/phys_par.html']
const moonParameters: Source = ['Физические параметры спутников · JPL', 'https://ssd.jpl.nasa.gov/sats/phys_par/']
const moonOrbits: Source = ['Оценки средних орбит спутников · JPL', 'https://ssd.jpl.nasa.gov/sats/elem/']

interface MoonDetails {
  id: string
  name: string
  englishName: string
  primary: string
  radius: string
  period: string
  overview: string
  fact: string
  history: readonly [date: string, description: string]
  source: string
}

function moon({ id, name, englishName, primary, radius, period, overview, fact, history, source }: MoonDetails): Entry {
  return {
    id, name, englishName, category: 'moon',
    classification: 'Естественный спутник',
    profile: {
      overview,
      properties: [
        ['Центральное тело', primary],
        ['Средний радиус', radius],
        ['Орбитальный период', period],
      ],
      fact,
      history: [history],
      references: [[name + ' · NASA Science', source], moonParameters, moonOrbits],
    },
  }
}

